import CryptoKit
import Foundation

/// The account's root key and everything derived from it (PROTOCOL.md §2).
///
/// Only `rootKey` needs storing (Keychain); everything else is derived. The
/// type's `description` is redacted, so printing or logging a value never
/// leaks key material.
public struct LumeCloudKeys: Sendable, Hashable {
    /// Byte length of the root key and of each derived key.
    public static let keyByteCount = 32
    /// Version byte of the record envelope this Kit writes and reads.
    public static let envelopeVersion: UInt8 = 0x01

    static let nonceByteCount = 12
    static let tagByteCount = 16

    /// HKDF `info` strings (§2.1).
    enum Info {
        static let enc = "lume-cloud/v1/enc"
        static let id = "lume-cloud/v1/id"
        static let auth = "lume-cloud/v1/auth"
    }

    /// 32 random bytes generated by the device that created the account.
    public let rootKey: Data
    /// AES-256-GCM key for record envelopes.
    public let encKey: Data
    /// HMAC-SHA256 key for record ids.
    public let idKey: Data
    /// The bearer secret. Its SHA-256 is the server's `authVerifier`.
    public let authKey: Data

    /// Throws `.invalidKeyLength` unless `rootKey` is exactly 32 bytes.
    public init(rootKey: Data) throws {
        guard rootKey.count == Self.keyByteCount else {
            throw LumeCloudCryptoError.invalidKeyLength(expected: Self.keyByteCount)
        }
        let rootKey = Data(rootKey) // re-base indices to 0
        self.rootKey = rootKey
        encKey = Self.hkdf(rootKey, info: Info.enc)
        idKey = Self.hkdf(rootKey, info: Info.id)
        authKey = Self.hkdf(rootKey, info: Info.auth)
    }

    /// Fresh keys from a cryptographically secure random root key.
    public static func generate() -> LumeCloudKeys {
        let key = SymmetricKey(size: .bits256)
        let bytes = key.withUnsafeBytes { Data($0) }
        // A 32-byte key always passes the length check.
        return try! LumeCloudKeys(rootKey: bytes) // swiftlint:disable:this force_try
    }

    // MARK: - Auth (§2.2)

    /// `base64url(SHA-256(authKey))`, sent once at account creation.
    public var authVerifier: String {
        Base64URL.encode(Data(SHA256.hash(data: authKey)))
    }

    /// `base64url(authKey)`: the secret half of the `Authorization` header.
    public var authToken: String {
        Base64URL.encode(authKey)
    }

    // MARK: - Record id (§2.3)

    /// `base64url(HMAC-SHA256(idKey, UTF8(logicalKey)))` — 43 characters,
    /// identical on every device holding the account key.
    public func recordID(for logicalKey: String) -> String {
        let mac = HMAC<SHA256>.authenticationCode(
            for: Data(logicalKey.utf8),
            using: SymmetricKey(data: idKey)
        )
        return Base64URL.encode(Data(mac))
    }

    // MARK: - Envelope (§2.4)

    /// Encrypts `plaintext` for the record `rid` with a fresh random nonce and
    /// returns the base64url wire form of `0x01 || nonce || ciphertext || tag`.
    public func seal(_ plaintext: Data, rid: String) throws -> String {
        try seal(plaintext, rid: rid, nonce: AES.GCM.Nonce())
    }

    /// `seal` with an injected nonce — for known-answer vectors only. Never
    /// reuse a nonce in production.
    func seal(_ plaintext: Data, rid: String, nonce nonceBytes: Data) throws -> String {
        guard nonceBytes.count == Self.nonceByteCount else {
            throw LumeCloudCryptoError.invalidKeyLength(expected: Self.nonceByteCount)
        }
        return try seal(plaintext, rid: rid, nonce: AES.GCM.Nonce(data: nonceBytes))
    }

    private func seal(_ plaintext: Data, rid: String, nonce: AES.GCM.Nonce) throws -> String {
        let box = try AES.GCM.seal(
            plaintext,
            using: SymmetricKey(data: encKey),
            nonce: nonce,
            authenticating: Data(rid.utf8)
        )
        var envelope = Data([Self.envelopeVersion])
        envelope.append(contentsOf: nonce)
        envelope.append(box.ciphertext)
        envelope.append(box.tag)
        return Base64URL.encode(envelope)
    }

    /// Decrypts a wire envelope for the record `rid`.
    ///
    /// Throws `.unsupportedEnvelopeVersion` for an unknown version byte (skip
    /// and keep that record), `.authenticationFailed` for a wrong `rid`, wrong
    /// key or tampered data, and `.invalidBase64`/`.malformedEnvelope` for
    /// garbage.
    public func open(_ wire: String, rid: String) throws -> Data {
        guard let envelope = Base64URL.decode(wire) else {
            throw LumeCloudCryptoError.invalidBase64
        }
        guard let version = envelope.first else {
            throw LumeCloudCryptoError.malformedEnvelope
        }
        guard version == Self.envelopeVersion else {
            throw LumeCloudCryptoError.unsupportedEnvelopeVersion(version)
        }
        guard envelope.count >= 1 + Self.nonceByteCount + Self.tagByteCount else {
            throw LumeCloudCryptoError.malformedEnvelope
        }
        let bytes = [UInt8](envelope)
        let nonceEnd = 1 + Self.nonceByteCount
        let tagStart = bytes.count - Self.tagByteCount
        do {
            let box = try AES.GCM.SealedBox(
                nonce: AES.GCM.Nonce(data: bytes[1 ..< nonceEnd]),
                ciphertext: bytes[nonceEnd ..< tagStart],
                tag: bytes[tagStart...]
            )
            return try AES.GCM.open(box, using: SymmetricKey(data: encKey), authenticating: Data(rid.utf8))
        } catch {
            throw LumeCloudCryptoError.authenticationFailed
        }
    }

    // MARK: - Helpers

    /// HKDF-SHA256 with an empty salt and IKM = `ikm`, 32 bytes out (§2.1).
    static func hkdf(_ ikm: Data, info: String) -> Data {
        let key = HKDF<SHA256>.deriveKey(
            inputKeyMaterial: SymmetricKey(data: ikm),
            salt: Data(),
            info: Data(info.utf8),
            outputByteCount: keyByteCount
        )
        return key.withUnsafeBytes { Data($0) }
    }
}

extension LumeCloudKeys: CustomStringConvertible, CustomDebugStringConvertible, CustomReflectable {
    public var description: String { "LumeCloudKeys(<redacted>)" }
    public var debugDescription: String { description }
    /// No children, so `dump(_:)` and debugger summaries can't print the keys either.
    public var customMirror: Mirror { Mirror(self, children: [:]) }
}
